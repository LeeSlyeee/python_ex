# =============================================================================
# [1] 라이브러리 임포트 (Library Import)
# =============================================================================
import os  # 운영체제 상호작용 (환경변수 접근 등)
from dotenv import load_dotenv  # .env 파일의 환경변수(API Key 등)를 로드
from langchain_classic.chat_models import ChatOpenAI  # OpenAI의 챗 모델(GPT)을 사용하기 위한 클래스
from langchain_classic.agents import load_tools  # 에이전트가 사용할 도구(Tools)들을 로드하는 함수
from langchain_classic.agents import initialize_agent  # 로드된 도구와 LLM을 결합하여 에이전트를 생성하는 함수
from langchain_classic.agents import AgentType  # 에이전트의 유형(Type)을 정의하는 열거형(Enum) 클래스

# =============================================================================
# [2] 환경 변수 설정 (Environment Setup)
# =============================================================================
# .env 파일에 저장된 API 키 값을 시스템 환경변수로 로드하여 모델이 사용할 수 있게 합니다.
load_dotenv()
OPENAI_API_KEY = os.getenv("OPENAI_API_KEY")

# =============================================================================
# [3] LLM 모델 초기화 (Initialize LLM)
# =============================================================================
# 답변을 생성하고 추론할 '두뇌' 역할을 하는 LLM 객체를 생성합니다.
# temperature=0: 창의성보다는 정확하고 논리적인 답변을 위해 0으로 설정합니다.
# model_name='gpt-4.1-mini': 사용할 모델 버전을 지정합니다. (참고: 실제 존재하는 모델명인지 확인 필요, 보통 gpt-4o-mini 등 사용)
llm = ChatOpenAI(temperature=0, model_name='gpt-4o-mini')

# =============================================================================
# [4] 도구 로드 (Load Tools)
# =============================================================================
# 에이전트가 사용할 '무기'들을 장착합니다.
# "wikipedia": 위키백과 검색을 통해 외부 지식을 찾을 수 있는 도구
# "llm-math": LLM 자체의 연산 능력 부족을 보완하기 위해, 수식을 계산해주는 계산기 도구 (llm 객체 필요)
tools = load_tools(["wikipedia", "llm-math"], llm=llm)

# =============================================================================
# [5] 에이전트 초기화 (Initialize Agent)
# =============================================================================
# 도구와 두뇌를 결합하여 스스로 생각하고 행동하는 '에이전트'를 만듭니다.
# AgentType.ZERO_SHOT_REACT_DESCRIPTION:
#   - Zero Shot: 별도의 예시(Few-shot) 없이도 작업을 수행
#   - ReAct: Reasoning(추론) + Acting(행동) 과정을 반복하며 답을 찾아가는 방식
#   - Description: 도구의 설명을 보고 상황에 맞는 도구를 스스로 선택함
# verbose=True: 에이전트의 생각 과정(추론 -> 행동 -> 관찰)을 터미널에 상세히 출력합니다.
agent = initialize_agent(
    tools, 
    llm, 
    agent=AgentType.ZERO_SHOT_REACT_DESCRIPTION, 
    description='계산이 필요할 때 사용', 
    verbose=True
)

# =============================================================================
# [6] 에이전트 실행 및 결과 출력 (Run Agent)
# =============================================================================
# 복합적인 질문을 던집니다. (정보 검색 + 수학 계산 필요)
# 1. "에드 시런이 태어난 해는?": 위키백과 검색 도구 사용 예상
# 2. "2026년도 현재 에드 시런은 몇 살?": 검색된 생년과 2026년을 이용해 계산기 도구 사용 예상
print("\n--- [6] 에이전트 실행 결과 ---")
print(agent.run("에드 시런이 태어난 해는? 2026년도 현재 에드 시런은 몇 살?"))